#!/usr/bin/env python3
"""DAMage CTRL Full Demo & Verification Runner.
Executes the entire workflow end-to-end:
  1. Installs/verifies required dependencies
  2. Scans original demo_app -> verifies 5 vulnerabilities, 1 false positive
  3. Fixes project -> creates patched copy, applies deterministic patches, validates compilation
  4. Runs security exploit suite -> confirms 3/3 exploits work on original and 3/3 blocked on patched
  5. Runs regression suite -> confirms 4/4 legitimate features pass on patched (home, login, notes, download)
  6. Re-scans patched copy -> confirms 0 vulnerabilities remain, false positive safely cleared
  7. Validates FastAPI endpoints
"""
import io
import json
import os
import shutil
import sys
import uuid
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import engine
import main
from tests.security import run_security_suite
from tests.regression import run_regression_suite
from fastapi.testclient import TestClient


def main_demo():
    print("=" * 80)
    print("           DAMage CTRL: FIND THE FLAW. PROVE THE FIX.")
    print("           Automated Stage-Hardened Security & Remediation Demo")
    print("=" * 80)

    # 1. Verification of environment
    print("\n[STEP 1/6] Verifying Target Application Environment...")
    demo_app_dir = ROOT / "demo_app"
    assert demo_app_dir.exists(), f"Demo app not found at {demo_app_dir}"
    print("  [OK] demo_app source directory ready.")

    # 2. Scan original demo_app
    print("\n[STEP 2/6] Running Detector Scan against ORIGINAL demo_app...")
    scan_res = engine.scan_project(demo_app_dir)
    counts = scan_res["counts"]
    findings = scan_res["findings"]

    print(f"  Observed Total Findings: {counts['total']}")
    print(f"  * Vulnerabilities: {counts['vuln']} (Critical: {counts['critical']}, High: {counts['high']}, Medium: {counts['medium']})")
    print(f"  * Safe False-Positives: {counts['false_positive']}")

    for f in findings:
        status_tag = "[VULN]" if f["status"] == "vuln" else "[SAFE / FP]"
        print(f"    - {status_tag} {f['id']} | {f['rule']} ({f['severity']}) line {f['line']}: {f['title']}")

    assert counts["vuln"] == 5, f"Expected 5 vulnerabilities, observed {counts['vuln']}"
    assert counts["false_positive"] == 1, f"Expected 1 false positive, observed {counts['false_positive']}"
    print("  [OK] Detector accurately identified all 5 planted vulnerabilities and cleared the 1 false positive.")

    # 3. Fix project: original -> patched copy
    demo_id = f"demo_run_{uuid.uuid4().hex[:8]}"
    workspace_dir = ROOT / "workspace" / demo_id
    orig_copy = workspace_dir / "original"
    patch_copy = workspace_dir / "patched"

    orig_copy.mkdir(parents=True, exist_ok=True)
    shutil.copytree(demo_app_dir, orig_copy, dirs_exist_ok=True)

    print(f"\n[STEP 3/6] Applying Deterministic Fixes to Copy (/workspace/{demo_id}/patched)...")
    fix_res = engine.fix_project(orig_copy, patch_copy)

    diff = fix_res["diff"]
    reverted = fix_res["reverted_files"]
    print("  Unified Diff Generated by difflib:")
    print("  " + "-" * 60)
    for line in diff.splitlines()[:18]:
        print(f"  {line}")
    if len(diff.splitlines()) > 18:
        print(f"  ... [{len(diff.splitlines()) - 18} more lines of unified diff]")
    print("  " + "-" * 60)
    print(f"  Auto-reverted files (compilation errors): {len(reverted)}")
    assert len(reverted) == 0, f"Expected 0 auto-reverted files, got: {reverted}"
    print("  [OK] All patched files passed Python compiler (py_compile) validation.")

    # 4. Security Exploit Suite (Original vs Patched)
    print("\n[STEP 4/6] Executing Real Security Exploits (Proof of Flaw & Proof of Fix)...")
    sec_results = run_security_suite(orig_copy, patch_copy)
    assert sec_results["all_confirmed_before"], "All exploits must succeed against the original unpatched app"
    assert sec_results["all_blocked_after"], "All exploits must be blocked against the patched app"
    print("  [OK] Security Exploit Suite PASSED: 3/3 exploits succeeded on original and were 100% BLOCKED on patched app.")

    # 5. Functional Regression Suite on Patched App
    print("\n[STEP 5/6] Executing Functional Regression Tests on PATCHED App...")
    reg_results = run_regression_suite(patch_copy)
    assert reg_results["all_passed"], f"Some regression tests failed: {reg_results}"
    print(f"  [OK] Functional Regression Suite PASSED: {reg_results['passed']}/{reg_results['total']} tests passed with 100% integrity.")

    # 6. Re-scan of Patched Copy & API Endpoints
    print("\n[STEP 6/6] Re-scanning Patched Project Copy & Validating REST API...")
    rescan_res = engine.scan_project(patch_copy)
    rescan_counts = rescan_res["counts"]
    print(f"  Patched Project Findings: {rescan_counts['total']}")
    print(f"  * Vulnerabilities: {rescan_counts['vuln']}")
    print(f"  * Safe False-Positives: {rescan_counts['false_positive']}")
    assert rescan_counts["vuln"] == 0, f"Expected 0 vulnerabilities, got {rescan_counts['vuln']}"
    assert rescan_counts["false_positive"] == 1, f"Expected 1 false positive, got {rescan_counts['false_positive']}"

    # Verify FastAPI endpoints
    client = TestClient(main.app)
    r_demo = client.post("/api/demo")
    assert r_demo.status_code == 200
    p_id = r_demo.json()["project_id"]

    r_scan = client.post(f"/api/{p_id}/scan")
    assert r_scan.status_code == 200
    assert r_scan.json()["counts"]["vuln"] == 5

    r_fix = client.post(f"/api/{p_id}/fix")
    assert r_fix.status_code == 200
    assert r_fix.json()["after_counts"]["vuln"] == 0
    assert r_fix.json()["security_proof"]["all_blocked_after"] is True
    assert r_fix.json()["regression_proof"]["all_passed"] is True

    r_rescan = client.post(f"/api/{p_id}/rescan")
    assert r_rescan.status_code == 200
    assert r_rescan.json()["counts"]["vuln"] == 0

    r_download = client.get(f"/api/{p_id}/download")
    assert r_download.status_code == 200
    assert r_download.headers["content-type"] == "application/zip"
    print("  [OK] REST API endpoints (/api/demo, /scan, /fix, /rescan, /download) verified.")

    print("\n" + "=" * 80)
    print("                     ALL STAGE CHECKS PASSED (100%)")
    print("=" * 80)
    print("SUMMARY:")
    print("  1. Original Demo:       5 Vulnerabilities, 1 False Positive")
    print("  2. Security Exploits:   3/3 Confirmed on Original -> 3/3 BLOCKED on Patched")
    print("  3. Functional Features: 4/4 Regression Tests Passed on Patched")
    print("  4. Final Re-scan:       0 Vulnerabilities, 1 Safe False Positive (Verified)")
    print("  5. REST API:            All Endpoints Active and Functional")
    print("=" * 80)


if __name__ == "__main__":
    main_demo()
